// Prints supabase/seed.sql from the bundled content, so the app and the database never drift.
// Run with: npm run seed:sql -w @wcic/content
import { STAPLES, STAPLE_ALIASES } from '../../matching/src/staples.ts';
import { RECIPES } from '../src/recipes.ts';
import { TERMS } from '../src/terms.ts';

const q = (v: string | number | boolean | null | undefined): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
};

const out: string[] = ['-- Generated by packages/content/scripts/to-seed-sql.ts. Do not edit by hand.', ''];

const names = new Set<string>(STAPLES);
for (const r of RECIPES) for (const i of r.ingredients) names.add(i.ingredient);
const staples = new Set<string>(STAPLES);
out.push('insert into ingredients (name, is_staple) values');
out.push([...names].sort().map((n) => `  (${q(n)}, ${staples.has(n)})`).join(',\n') + ';', '');

out.push('insert into ingredient_aliases (alias, ingredient_id)');
out.push('select a.alias, i.id from (values');
out.push(Object.entries(STAPLE_ALIASES).map(([a, n]) => `  (${q(a)}, ${q(n)})`).join(',\n'));
out.push(') as a (alias, name) join ingredients i on i.name = a.name;', '');

for (const r of RECIPES) {
  out.push(`with r as (`);
  out.push(`  insert into recipes (slug, title, minutes, difficulty) values (${q(r.slug)}, ${q(r.title)}, ${r.minutes}, ${q(r.difficulty)}) returning id`);
  out.push(`), ing as (`);
  out.push(`  insert into recipe_ingredients (recipe_id, ingredient_id, position, amount, unit, optional)`);
  out.push(`  select r.id, i.id, v.position, v.amount, v.unit, v.optional from r, (values`);
  out.push(
    r.ingredients
      .map((i, n) => `    (${q(i.ingredient)}, ${n + 1}, ${i.amount ?? 'null'}::numeric, ${q(i.unit)}, ${i.optional ?? false})`)
      .join(',\n'),
  );
  out.push(`  ) as v (name, position, amount, unit, optional) join ingredients i on i.name = v.name`);
  out.push(`)`);
  out.push(`insert into recipe_steps (recipe_id, position, text) select r.id, v.position, v.text from r, (values`);
  out.push(r.steps.map((s, n) => `  (${n + 1}, ${q(s)})`).join(',\n'));
  out.push(`) as v (position, text);`, '');
}

out.push('insert into terms (slug, name, part_of_speech, short_definition, full_definition, guide_title, guide, related) values');
out.push(
  TERMS.map(
    (t) =>
      `  (${q(t.slug)}, ${q(t.name)}, ${q(t.partOfSpeech)}, ${q(t.shortDefinition)}, ${q(t.fullDefinition)}, ${q(t.guideTitle)}, ${
        t.guide ? `${q(JSON.stringify(t.guide))}::jsonb` : 'null'
      }, ${q(`{${t.related.join(',')}}`)})`,
  ).join(',\n') + ';',
);

console.log(out.join('\n'));
